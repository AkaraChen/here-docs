const COMMON = new Set([...SIMPLIFIED, ...TRADITIONAL, ...KOREAN]);

/** Share of non-ASCII characters that are common in natural CJK text; replacement characters count against it. */
export function cjkPlausibility(text: string): number {
  let total = 0;
  let score = 0;
  for (const char of text) {
    const code = char.codePointAt(0)!;
    if (code < 0x80) {
      continue;
    }
    total += 1;
    if (code === 0xfffd) {
      score -= 2;
    } else if (COMMON.has(char) || (code >= 0x3041 && code <= 0x30ff)) {
      score += 1;
    } else if ((code >= 0x3000 && code <= 0x303f) || (code >= 0xff01 && code <= 0xff5e)) {
      score += 0.5;
    }
  }
  return total === 0 ? 0 : score / total;
}
